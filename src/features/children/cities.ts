/** Значение профиля — русское название города; пустая строка — «не знаю». */
export const cityNames = cityGroups.flatMap((g) => g.cities.map((c) => c.ru));

export function cityLabel(name: string, locale: Locale) {
  for (const group of cityGroups) {
    const city = group.cities.find((c) => c.ru === name);
    if (city) return city[locale];
  }
  return name;
}
