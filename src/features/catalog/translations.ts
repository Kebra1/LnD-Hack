export function localizeOffering(item: Offering, locale: Locale): Offering {
  if (locale === "ru") return item;
  const text = kk[item.id];
  if (!text) throw new Error(`Missing demo translation: ${item.id}`);
  return {
    ...item,
    ...text,
    kind: item.kind === "Центр" ? "Орталық" : "Маман",
    source: `demo-catalog-v2 / ${item.id}: ойдан шығарылған оқу жазбасы. Тексерілген ұсыныс емес.`,
  };
}
